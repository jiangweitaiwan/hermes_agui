import { expect, test } from "@playwright/test";

test("owner creates, chats, edits, disables, enables and soft-deletes a native Bot", async ({ page }) => {
  test.skip(process.env.DYNAMIC_BOT_TEST !== "1", "managed Host fixture only");
  await page.goto("/");
  const login = page.getByRole("form", { name: "管理登入" });
  await login.getByLabel("存取金鑰").fill("browser-owner-secret");
  await login.getByRole("button", { name: "登入", exact: true }).click();
  await page.getByRole("button", { name: "新增 Bot", exact: true }).click();
  const form = page.getByRole("form", { name: "建立 Bot", exact: true });
  await form.getByLabel("Bot 名稱").fill("Financial Analyst");
  await form.getByLabel("說明").fill("Analyze company finances.");
  await form.getByLabel("memory", { exact: true }).check();
  await form.getByRole("button", { name: "建立 Bot", exact: true }).click();
  const nav = page.getByRole("navigation", { name: "Bot 列表" });
  await expect(nav.getByRole("button", { name: "Financial Analyst", exact: true })).toBeVisible();
  const chat = page.locator("section:visible");
  await expect(chat.getByRole("status")).toHaveText("已連線");
  await chat.locator("textarea").fill("hello alpha");
  await chat.locator("textarea").press("Enter");
  await expect(chat).toContainText("Alpha private answer.");
  const firstThread = await chat.getAttribute("data-thread-id");
  await page.getByRole("button", { name: "Bot Manager", exact: true }).click();
  await page.getByRole("button", { name: "新增 Bot", exact: true }).click();
  await form.getByLabel("Bot 名稱").fill("Reviewer B");
  await form.getByLabel("memory", { exact: true }).check();
  await form.getByRole("button", { name: "建立 Bot", exact: true }).click();
  await expect(chat.getByRole("status")).toHaveText("已連線");
  await chat.locator("textarea").fill("hello beta");
  await chat.locator("textarea").press("Enter");
  await expect(chat).toContainText("Beta private answer.");
  await expect(chat).not.toContainText("Alpha private answer.");
  await nav.getByRole("button", { name: "Financial Analyst", exact: true }).click();
  await expect(chat).toHaveAttribute("data-thread-id", firstThread!);
  await expect(chat).toContainText("Alpha private answer.");
  await page.getByRole("button", { name: "新增對話", exact: true }).click();
  await expect(chat).not.toContainText("Alpha private answer.");
  await page.getByRole("button", { name: "對話 1", exact: true }).click();
  await expect(chat).toContainText("Alpha private answer.");
  await page.getByRole("button", { name: "Bot Manager", exact: true }).click();
  await page.getByRole("button", { name: "編輯 Financial Analyst", exact: true }).click();
  const edit = page.getByRole("form", { name: "編輯 Bot", exact: true });
  await edit.getByLabel("Bot 名稱").fill("Financial Analyst Updated");
  await edit.getByRole("button", { name: "儲存 Bot", exact: true }).click();
  await expect(nav.getByRole("button", { name: "Financial Analyst Updated", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "停用 Financial Analyst Updated", exact: true }).click();
  await expect(nav.getByRole("button", { name: "Financial Analyst Updated", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "啟用／重試 Financial Analyst Updated", exact: true }).click();
  await expect(nav.getByRole("button", { name: "Financial Analyst Updated", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "刪除 Financial Analyst Updated", exact: true }).click();
  await page.getByRole("button", { name: "確認刪除", exact: true }).click();
  await expect(nav.getByRole("button", { name: "Financial Analyst Updated", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "編輯 Financial Analyst Updated", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "登出", exact: true }).click();
  await expect(page.getByRole("form", { name: "管理登入" })).toBeVisible();
  await expect(page.locator("section[data-thread-id]")).toHaveCount(0);
  await expect(nav.getByRole("button")).toHaveCount(0);
});

test("workspace handles allowlists, duplicate submit, lifecycle failures, logout and mobile navigation", async ({ page }) => {
  let loggedIn = false;
  let creates = 0;
  let release: (() => void) | undefined;
  let records: Record<string, unknown>[] = [];
  const template = { id: "one", name: "One", harness: "hermes", provider: "custom", model: "fake", skills: ["research"], toolsets: ["memory"] };
  await page.route("**/api/bot-session", async route => {
    loggedIn = route.request().method() === "POST";
    await route.fulfill({ status: loggedIn ? 200 : 204, body: loggedIn ? "{}" : undefined });
  });
  await page.route("**/api/bots**", async route => {
    const request = route.request();
    const path = new URL(request.url()).pathname;
    if (!loggedIn) return route.fulfill({ status: 401, json: { error: "Authentication required" } });
    if (path.endsWith("/options")) return route.fulfill({ json: [template, { ...template, id: "two", name: "Two", skills: [], toolsets: [] }] });
    if (path.endsWith("/enable")) return route.fulfill({ status: 403, json: { error: "Owner access denied" } });
    if (request.method() === "POST") {
      creates++;
      await new Promise<void>(resolve => { release = resolve; });
      const input = request.postDataJSON();
      expect(input.skills).toEqual([]);
      expect(input.toolsets).toEqual([]);
      expect(Object.keys(input).sort()).toEqual(["name", "description", "templateId", "harness", "skills", "toolsets", "delegationTargets"].sort());
      records = [{ ...input, id: "bot-test", status: "failed" },
        { ...input, id: "bot-disabled", name: "Paused bot", status: "disabled" },
        { ...input, id: "bot-starting", name: "Starting bot", status: "provisioning" }];
      return route.fulfill({ status: 503, json: { error: "Provisioning unavailable; retry" } });
    }
    return route.fulfill({ json: records });
  });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await page.getByLabel("存取金鑰").fill("owner-a");
  await page.getByRole("button", { name: "登入", exact: true }).click();
  await page.getByRole("button", { name: "新增 Bot", exact: true }).click();
  const form = page.getByRole("form", { name: "建立 Bot", exact: true });
  await form.getByLabel("Bot 名稱").fill("Failed bot");
  await form.getByLabel("research", { exact: true }).check();
  await form.getByLabel("memory", { exact: true }).check();
  await form.getByLabel("Harness／模型").selectOption("two");
  await expect(form.getByRole("checkbox")).toHaveCount(0);
  const submit = form.getByRole("button", { name: "建立 Bot", exact: true });
  await submit.click();
  await expect(submit).toBeDisabled();
  await expect.poll(() => creates).toBe(1);
  release!();
  await expect(page.getByRole("dialog").getByRole("alert")).toContainText("Provisioning unavailable");
  await page.getByRole("button", { name: "關閉", exact: true }).click();
  await expect(page.getByRole("button", { name: "開啟 Failed bot", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "開啟 Paused bot", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "開啟 Starting bot", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "啟用／重試 Failed bot", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("Owner access denied");
  await page.getByRole("button", { name: "登出", exact: true }).click();
  await expect(page.getByRole("form", { name: "管理登入" })).toBeVisible();
  await expect(page.getByLabel("存取金鑰")).toHaveValue("");
  records = [];
  await page.getByLabel("存取金鑰").fill("owner-b");
  await page.getByRole("button", { name: "登入", exact: true }).click();
  await expect(page.getByText("Failed bot", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "工作空間導覽", exact: true }).click();
  await page.getByRole("button", { name: "Graph Memory", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Graph Memory Explorer", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
