test('UI clears delayed private responses, pages live windows and handles unavailable/denied states', async ({ page }) => {
  let release: (() => void) | undefined;
  let delayed = false, denied = false;
  await page.route('**/api/bots', r => r.fulfill({ json: ['a', 'b'] }));
  await page.route('**/api/bots/options', r => r.fulfill({ status: 503, json: {} }));
  const summary = (title: string) => ({ id: `bot_private:${title}`, pageId: title, title, visibility: 'bot_private', type: 'note', verification: 'unverified' });
  await page.route('**/api/graph/**', async route => {
    const url = new URL(route.request().url());
    if (denied) { await route.fulfill({ status: 404, json: {} }); return; }
    if (url.pathname.endsWith('/network') || url.pathname.endsWith('/pages')) {
      const title = url.searchParams.has('cursor') ? 'Second' : url.searchParams.get('scope') === 'project_shared' ? 'Shared' : 'Private';
      if (delayed && title === 'Private' && url.pathname.endsWith('/network')) await new Promise<void>(resolve => { release = resolve; });
      await route.fulfill({ json: { nodes: [summary(title)], pages: [summary(title)], partial: false, edges: [], nextCursor: title === 'Private' ? 'next' : null, truncated: title === 'Private' } }).catch(() => undefined);
    } else if (url.pathname.endsWith('/stats')) await route.fulfill({ json: { pages: 1, edges: 0, private: 1, shared: 0, partial: false } });
    else await route.fulfill({ status: 503, json: { status: 'unavailable' } });
  });
  await page.goto('/'); await page.getByRole('button', { name: 'Graph Memory', exact: true }).click();
  const list = page.getByRole('list', { name: 'Wiki pages', exact: true });
  await expect(list).toContainText('Private');
  await page.getByRole('button', { name: /Load more/ }).click();
  await expect(page.locator('.memory-graph')).toContainText('Second');
  await expect(list).toContainText('Private');
  await page.getByRole('button', { name: /Wiki next page/ }).click(); await expect(list).toContainText('Second'); await expect(list).not.toContainText('Private');
  delayed = true; await page.getByRole('button', { name: 'Refresh memory', exact: true }).click();
  await expect.poll(() => Boolean(release)).toBe(true);
  await page.getByRole('button', { name: 'Shared', exact: true }).click(); await expect(list).toContainText('Shared');
  release!(); await expect(list).not.toContainText('Private');
  await expect(page.getByRole('region', { name: 'Memory Evolution Dashboard' })).toContainText('not available');
  denied = true; await page.getByRole('button', { name: 'Refresh memory', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Unauthorized'); await expect(list).toHaveCount(0);
});
